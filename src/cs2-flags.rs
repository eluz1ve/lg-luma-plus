/// The file stem under `flags/` for a country, or none for a country without artwork.
pub fn code(country: &str) -> Option<&'static str> {
    COUNTRIES
        .iter()
        .find(|(name, _)| name.eq_ignore_ascii_case(country))
        .map(|(_, code)| *code)
}

